const pe = window.__pe
const S = () => pe.useApp.getState()
const wait = (ms) => new Promise((r) => setTimeout(r, ms))
S().setSettings({ theme: 'light' })
pe.io.newDocument('blank')
await wait(700)
const ed = pe.activeEditor()
ed.commands.setContent('<p>Some sample text to select and format with the mini toolbar.</p><p></p>')
ed.chain().focus('end').insertContent('/').run()
await wait(500)
await window.pe.dev.shot('m-slash')
ed.chain().focus().deleteRange({ from: ed.state.selection.from - 1, to: ed.state.selection.from }).run()
await wait(200)
ed.chain().focus().setTextSelection({ from: 6, to: 17 }).run()
await wait(500)
await window.pe.dev.shot('m-bubble')
const r = document.querySelector('.pe-doc p').getBoundingClientRect()
S().set({ contextMenu: { x: r.left + 60, y: r.top + 8, clientX: r.left + 60, clientY: r.top + 8, misspelledWord: 'smaple', dictionarySuggestions: ['sample', 'simple'], isEditable: true, selectionText: 'sample text', linkURL: '' } })
await wait(400)
await window.pe.dev.shot('m-context')
S().set({ contextMenu: null })
pe.commands.openFind(true)
await wait(400)
await window.pe.dev.shot('m-find')
return 'ok'

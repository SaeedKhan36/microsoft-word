const pe = window.__pe
const wait = (ms) => new Promise((r) => setTimeout(r, ms))
const log = []
await wait(800)
await window.pe.dev.shot('01-start')
pe.io.newDocument('report')
await wait(1500)
await window.pe.dev.shot('02-report')
const st = pe.useApp.getState()
log.push({ docs: st.docs.length, pages: st.docs[0]?.pagination.pages })
pe.io.newDocument('blank')
await wait(600)
const ed = pe.activeEditor()
ed.chain().focus().insertContent('<h1>Hello Personal Editor</h1><p>This is a <strong>test</strong> paragraph with some <em>italic</em> text.</p>').run()
for (let i = 0; i < 40; i++) ed.chain().insertContent('<p>Lorem ipsum dolor sit amet, consectetur adipiscing elit, sed do eiusmod tempor incididunt ut labore et dolore magna aliqua. Ut enim ad minim veniam, quis nostrud exercitation ullamco laboris.</p>').run()
await wait(1500)
await window.pe.dev.shot('03-typed')
log.push({ pages: pe.useApp.getState().docs[1].pagination.pages, stats: pe.useApp.getState().docs[1].stats })
pe.useApp.getState().set({ ribbonTab: 'insert' })
await wait(300)
await window.pe.dev.shot('04-insert')
pe.useApp.getState().set({ backstage: 'print' })
await wait(1500)
await window.pe.dev.shot('05-print')
pe.useApp.getState().set({ backstage: null })
pe.useApp.getState().setSettings({ theme: 'dark' })
await wait(500)
await window.pe.dev.shot('06-dark')
pe.useApp.getState().setSettings({ theme: 'system' })
return log

const pe = window.__pe
const S = () => pe.useApp.getState()
const wait = (ms) => new Promise((r) => setTimeout(r, ms))
S().setSettings({ theme: 'light' })
pe.io.newDocument('journal')
await wait(1200)
const ed = pe.activeEditor()
S().set({ draw: { ...S().draw, tool: 'pen' }, ribbonTab: 'draw' })
await wait(300)
const ink = document.querySelector('.pe-ink')
ink.scrollIntoView({ block: 'center' })
await wait(300)
const r = ink.getBoundingClientRect()
const fire = (type, x, y, id = 7) => ink.dispatchEvent(new PointerEvent(type, { bubbles: true, cancelable: true, pointerId: id, pointerType: 'pen', pressure: 0.6, clientX: r.left + x, clientY: r.top + y, button: 0, buttons: type === 'pointerup' ? 0 : 1 }))
// write a wavy line and a box
fire('pointerdown', 40, 60)
for (let i = 1; i <= 30; i++) fire('pointermove', 40 + i * 12, 60 + Math.sin(i / 3) * 18)
fire('pointerup', 400, 60)
await wait(100)
fire('pointerdown', 80, 160, 8)
for (const [x, y] of [[260,160],[260,260],[80,260],[80,162]]) for (let k = 1; k <= 8; k++) fire('pointermove', 80 + (x - 80) * k / 8, 160 + (y - 160) * k / 8, 8)
fire('pointerup', 80, 162, 8)
await wait(300)
let strokes = 0
ed.state.doc.descendants((n) => { if (n.type.name === 'ink') strokes += n.attrs.strokes.length; return true })
await window.pe.dev.shot('draw')
S().set({ draw: { ...S().draw, tool: 'select' }, ribbonTab: 'home' })
S().set({ backstage: 'home' })
await wait(500)
await window.pe.dev.shot('home-light')
return { strokes, undo: ed.can().undo() }
